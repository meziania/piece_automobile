const originals = new Map();
const params = new URLSearchParams(location.search);
const requested = params.get("lang");
let lang = requested === "ar" || requested === "fr"
  ? requested
  : localStorage.getItem("questionnaire-lang") === "ar" ? "ar" : "fr";

function t(fr) {
  if (lang !== "ar" || fr == null) return fr;
  return dict[fr] ?? fr;
}

function remember(node) {
  if (originals.has(node) || !node.nodeValue.trim()) return;
  const parent = node.parentElement;
  if (!parent || parent.closest("script, style, .brand, .lang, .hp, #reviewList, .marge, #stepLabel, #error, #thanksText, #next")) return;
  originals.set(node, node.nodeValue);
}

function capture(root) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node = walker.nextNode();
  while (node) {
    remember(node);
    node = walker.nextNode();
  }
}

function applyStatic() {
  document.documentElement.lang = lang === "ar" ? "ar" : "fr";
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  document.title = t("Questionnaire pièces auto — Salmiya 2");
  originals.forEach((original, node) => {
    if (!node.isConnected) return;
    const trimmed = original.trim();
    const translated = t(trimmed);
    node.nodeValue = original.replace(trimmed, translated);
  });
  document.querySelectorAll("[placeholder]").forEach((el) => {
    if (!el.dataset.ph) el.dataset.ph = el.getAttribute("placeholder");
    el.placeholder = t(el.dataset.ph);
  });
  document.querySelectorAll("[aria-label]").forEach((el) => {
    if (!el.dataset.aria) el.dataset.aria = el.getAttribute("aria-label");
    el.setAttribute("aria-label", t(el.dataset.aria));
  });
  document.querySelectorAll("img[alt]").forEach((el) => {
    if (!el.dataset.alt) el.dataset.alt = el.getAttribute("alt");
    el.alt = t(el.dataset.alt);
  });
  document.querySelectorAll("[data-lang]").forEach((button) => {
    const on = button.dataset.lang === lang;
    button.classList.toggle("is-on", on);
    button.setAttribute("aria-pressed", on ? "true" : "false");
  });
}

function setLang(next) {
  if (next !== "ar" && next !== "fr") return;
  lang = next;
  localStorage.setItem("questionnaire-lang", lang);
  applyStatic();
  document.dispatchEvent(new Event("langchange"));
}

document.querySelectorAll("[data-lang]").forEach((button) => {
  button.addEventListener("click", () => setLang(button.dataset.lang));
});

capture(document.body);
window.t = t;
window.currentLang = () => lang;
